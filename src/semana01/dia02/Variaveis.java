package semana01.dia02;

public class Variaveis {
    public static void main(String[] args){

        // Java e uma linguagem fortemente tipada.

        byte byte1 = 127; // 8 bits ou 1 byte
        short short1 = 32767; // 16 bits ou 2 bytes
        int inteiro = 2147483647; // 32 bits ou 4 bytes
        long longo = 2147483647L; // 64 bits ou 8 bytes
        float float1 = 3.14f; // 32 bits ou 4 bytes
        double double1 = 3.141592653589793; // 64 bits ou  8 bytes
        boolean boleano = true; // 1 bit ou 1 byte
        char caractere = 'a'; // 16 bits ou 2 bytes vai do  \u0000 ate o \uffff

        System.out.println(byte1);
        System.out.println(short1);
        System.out.println(inteiro);
        System.out.println(longo);
        System.out.println(float1);
        System.out.println(double1);
        System.out.println(boleano);
        System.out.println(caractere);
    }
}
